import type{SiteTemplatePageProps}from'../../../types'
import{pageBySlug}from'../content/data'
import{Article}from'./Article'
import{ServicesIndex}from'./ServicesIndex'
import{WorkIndex}from'./WorkIndex'
import{Journal}from'./Journal'
import{Careers}from'./Careers'
import{Contact}from'./Contact'
import{Detail}from'./Detail'
import{PricingPage}from'./PricingPage'
import{Service}from'./Service'
import{Member}from'./Member'
import{Case}from'./Case'
import{About}from'./About'
export function Entry(props:SiteTemplatePageProps&{slug:string}){const page=pageBySlug(props.slug);if(props.slug==='about')return <About {...props} page={page}/>;if(props.slug.startsWith('work/'))return <Case {...props} page={page}/>;if(props.slug.startsWith('services/'))return <Service {...props}/>;if(props.slug.startsWith('team/'))return <Member {...props} page={page}/>;if(props.slug==='pricing')return <PricingPage {...props}/>;if(props.slug==='contact')return <Contact {...props} page={page}/>;if(props.slug==='services')return <ServicesIndex {...props} page={page}/>;if(props.slug==='work')return <WorkIndex {...props} page={page}/>;if(props.slug==='blog')return <Journal {...props}/>;if(props.slug==='careers')return <Careers {...props} page={page}/>;if(page.category==='article'||/^blog\//.test(props.slug)||['privacy','terms','cookies'].includes(props.slug))return <Article {...props} page={page}/>;return <Detail {...props} page={page}/>}
